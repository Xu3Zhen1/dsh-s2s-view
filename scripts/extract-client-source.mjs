/**
 * One-shot extraction: turn the hand-written `lib/client.js` into a build input.
 *
 * WHY THIS EXISTS
 *
 * `lib/client.js` was authored by hand directly inside `node_modules`, and
 * `lib/` is gitignored + produced by `pnpm build`. So the file was one `pnpm
 * install` away from disappearing with no copy anywhere on the machine — and
 * it held several fixed defects that existed nowhere else (the queue
 * double-emit, the per-workspace render cap, the theme-token names, the
 * message cards).
 *
 * This script splits that artifact into the two halves the upstream build
 * already knows how to produce, so the bytes stop being the source of truth:
 *
 *   preamble (generated by scripts/build-history-surface.mjs)
 *   + body   (src/client/index.js — now a tracked, editable file)
 *   + footer (generated)
 *
 * The body is stored VERBATIM, keeping the 4-space factory indentation it had
 * in the artifact. Re-indenting it would mean rewriting whitespace adjacent to
 * the CSS string literals, and the whole point here is that the rebuilt file
 * must be byte-identical to what is deployed today.
 *
 * Run once: node scripts/extract-client-source.mjs <path-to-baseline-client.js>
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const baseline = process.argv[2]
if (baseline === undefined) {
  console.error('usage: node scripts/extract-client-source.mjs <baseline client.js>')
  process.exit(2)
}

const source = readFileSync(baseline, 'utf8')

/**
 * The shell markers. These are the exact literals the upstream `clientBundle`
 * emits as its banner/intro/footer (see @dpskh/dsh-a2a tsdown.shared.ts), which
 * is why the artifact has this shape at all.
 */
const SHELL_OPEN = 'window.__ModuleLoader__.load({\n'
const INTRO = '    var module = { exports: {} }\n    var exports = module.exports\n'
const FOOTER = '\n    return module.exports\n  },\n})\n'

const shellAt = source.indexOf(SHELL_OPEN)
if (shellAt < 0) throw new Error('ModuleLoader shell not found — is this a client bundle?')

const introAt = source.indexOf(INTRO, shellAt)
if (introAt < 0) throw new Error('factory intro (`var module = { exports: {} }`) not found')

const bodyStart = introAt + INTRO.length
const footerAt = source.lastIndexOf(FOOTER)
if (footerAt < bodyStart) throw new Error('factory footer (`return module.exports`) not found')

const header = source.slice(0, shellAt)
const idLine = source.slice(shellAt, introAt)
const body = source.slice(bodyStart, footerAt)

/** The bundler id and factory opening line, kept verbatim between header and intro. */
const shellPrologue = idLine

const bodyFile = join(root, 'src', 'client', 'index.js')
mkdirSync(dirname(bodyFile), { recursive: true })
writeFileSync(bodyFile, body)

const metaFile = join(root, 'src', 'client', '.shell.json')
writeFileSync(metaFile, JSON.stringify({ header, shellPrologue, intro: INTRO, footer: FOOTER }, null, 2) + '\n')

console.log('header bytes   :', header.length)
console.log('shell prologue :', JSON.stringify(shellPrologue))
console.log('body bytes     :', body.length)
console.log('footer bytes   :', FOOTER.length)
console.log('')
console.log('wrote', bodyFile)
console.log('wrote', metaFile)
console.log('')
console.log('reassembly check:', header.length + shellPrologue.length + INTRO.length + body.length + FOOTER.length, 'vs source', source.length)
